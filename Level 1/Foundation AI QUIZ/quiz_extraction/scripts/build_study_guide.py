def rel(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def write_markdown() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    lines = [
        "# SuperAI SS6 Foundation AI Quiz - 100 Questions Review",
        "",
        "ไฟล์นี้ถอดจาก PDF ที่เป็นภาพแคปหน้าจอยาว พร้อมคำตอบที่เลือกในภาพ เฉลยแนะนำ และคำอธิบายสำหรับอ่านทบทวน",
        "",
        "หมายเหตุ: บางข้อในภาพมีคำตอบที่เลือกไว้ไม่ตรงกับหลักทั่วไป จึงแยก `คำตอบที่เลือกในภาพ` และ `เฉลยแนะนำ` ไว้ชัดเจน",
        "",
    ]
    for item in QUESTIONS:
        lines.append(f"## ข้อ {item['n']}")
        lines.append("")
        lines.append(f"**คำถาม:** {item['question']}")
        lines.append("")
        qcrop = CROPS_DIR / f"q{item['n']:03d}" / "question_full.png"
        lines.append(f"**ภาพข้อเต็ม:** [{rel(qcrop)}]({rel(qcrop)})")
        for fig in item["figures"]:
            lines.append("")
            lines.append(f"![ภาพประกอบข้อ {item['n']}]({fig})")
        lines.append("")
        lines.append("**ตัวเลือก:**")
        for opt in item["options"]:
            tags = []
            if opt == item["selected"]:
                tags.append("เลือกในภาพ")
            if opt == item["answer"]:
                tags.append("เฉลย")
            tag = f" ({', '.join(tags)})" if tags else ""
            lines.append(f"- {opt}{tag}")
        lines.append("")
        lines.append(f"**คำตอบที่เลือกในภาพ:** {item['selected']}")
        lines.append("")
        lines.append(f"**เฉลยแนะนำ:** {item['answer']}")
        lines.append("")
        lines.append(f"**อธิบาย:** {item['explanation']}")
        if item["note"]:
            lines.append("")
            lines.append(f"**หมายเหตุ:** {item['note']}")
        lines.append("")
    MD_OUT.write_text("\n".join(lines), encoding="utf-8")


def set_cell_shading(cell, fill: str) -> None:
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:fill"), fill)
    tc_pr.append(shd)


def set_cell_text(cell, text: str, bold=False, color=None) -> None:
    cell.text = ""
    p = cell.paragraphs[0]
    run = p.add_run(text)
    run.font.name = "Tahoma"
    run.font.size = Pt(9)
    run.bold = bold
    if color:
        run.font.color.rgb = RGBColor.from_string(color)


def add_label_detail(doc: Document, label: str, detail: str) -> None:
    table = doc.add_table(rows=1, cols=2)
    table.autofit = False
    table.columns[0].width = Inches(1.25)
    table.columns[1].width = Inches(5.0)
    set_cell_shading(table.cell(0, 0), "E8EEF5")
    set_cell_text(table.cell(0, 0), label, bold=True, color="1F4D78")
    set_cell_text(table.cell(0, 1), detail)


